        // Collect the path
        vector<int> path;
        int current = v;
        while (current != -1) 
        {
            path.push_back(current);
            current = parent[current];
        }
        reverse(path.begin(), path.end());
        
        // Print total stations
        cout << endl << "Minimum number of stations from " << stations[path.front()] 
             << " to " << stations[path.back()] << " are: " << path.size() - 1 << endl;
        
        // Print complete path
